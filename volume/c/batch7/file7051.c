// fichero 7051 -- utilidades static
static int util7051_0(int a, int b) {
    return a + b * 1;
}

static int util7051_1(int a, int b) {
    return a + b * 2;
}

static int util7051_2(int a, int b) {
    return a + b * 3;
}

static int util7051_3(int a, int b) {
    return a + b * 4;
}

int combinar7051(int a, int b) {
    return util7051_0(a, b);
}
