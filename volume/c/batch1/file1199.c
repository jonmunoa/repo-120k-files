// fichero 1199 -- utilidades static
static int util1199_0(int a, int b) {
    return a + b * 1;
}

static int util1199_1(int a, int b) {
    return a + b * 2;
}

static int util1199_2(int a, int b) {
    return a + b * 3;
}

static int util1199_3(int a, int b) {
    return a + b * 4;
}

int combinar1199(int a, int b) {
    return util1199_0(a, b);
}
